"""Загрузка поставляемых вместе с приложением запросов 1С."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Query1C:
    slug: str
    title: str
    description: str
    filename: str
    text: str
    parameters: tuple[tuple[str, str], ...]
    result_columns: tuple[tuple[str, str], ...]


_QUERY_DIR = Path(__file__).resolve().parent


def load_query_catalog() -> tuple[Query1C, ...]:
    """Return the checked-in query catalog in its display order."""
    query_path = _QUERY_DIR / "mass_outbound_orders.query"
    return (
        Query1C(
            slug="mass_outbound_orders",
            title="Расходные ордера — расчёт количества коробов",
            description=(
                "Выгружает строки Документ.РасходныйОрдерСклад и рассчитывает количество "
                "коробов по той же логике, что форма документа. Запрос проверен вручную "
                "сравнением с колонкой «Отгружено коробок». Приложение запрос не выполняет: "
                "пользователь копирует его в консоль 1С."
            ),
            filename=query_path.name,
            text=query_path.read_text(encoding="utf-8"),
            parameters=(
                ("ДатаНачала", "Начало периода включительно."),
                ("ДатаОкончания", "Конец периода исключительно."),
                ("Склады", "Список складов."),
            ),
            result_columns=(
                ("СсылкаРО", "Ссылка на расходный ордер."),
                ("НомерРО", "Номер расходного ордера."),
                ("ДатаРО", "Дата расходного ордера."),
                ("Склад", "Склад расходного ордера."),
                ("РЦ", "Распределительный центр — владелец склада."),
                ("НомерСтроки", "Номер строки расходного ордера."),
                ("КодНоменклатуры", "Код номенклатуры."),
                ("Номенклатура", "Номенклатура из строки РО."),
                ("КодХарактеристики", "Код характеристики номенклатуры."),
                ("Характеристика", "Характеристика номенклатуры."),
                ("ДатаПроизводства", "Дата производства из строки РО."),
                ("ЕдиницаИзмерения", "Единица измерения из строки РО."),
                ("Количество", "Количество из строки РО."),
                ("КоличествоВКоробке", "Количество единиц в коробке для расчёта."),
                ("РасчетноеОтгруженоКоробок", "Реконструированное количество коробов."),
                ("КонтрольРасчета", "Результат проверки исходных данных для расчёта."),
            ),
        ),
    )
